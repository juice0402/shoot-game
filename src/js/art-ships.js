function flameFrames(w,h,list,extra){
  const cols=['#fffff0','#ffec8c','#ffb032','#f0601e','#aa2828'];
  return [0,2,4,1].map(t=>{const c=document.createElement('canvas');c.width=w+4;c.height=h+4+extra;const g=c.getContext('2d');
    for(const [x0,x1,top,ln] of list){const L=ln+t,cx=(x0+x1)/2;
      for(let y=top;y<top+L;y++){const k=(y-top)/L,hw=(x1-x0+1)*(1-k*0.8)/2;
        for(let x=x0;x<=x1;x++){if(Math.abs(x-cx)>hw)continue;const ci=Math.min(4,Math.floor(k*4+Math.abs(x-cx)/(hw+.01)*1.5));g.fillStyle=cols[ci];g.fillRect(x+2,y+2,1,1);}}}
    return c;});
}
